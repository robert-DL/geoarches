#!/usr/bin/env python3
"""
One-off repair for NetCDF prediction files written by encode_dataset.py before
it inverted the log-transform for total_precipitation/olr (see log_variables
in configs/dataloader/era5-daily-s2s.yaml). Converts affected variables from
log-space back to physical units:

    physical = exp(log_value) - 1e-5

then clips the physically non-negative variables to >= 0 (matching
Rollout.truncate_non_negative() / era5_constants.non_negative_variables).

Only safe to use on single-forward-pass steps (max forecast step == 1), where
the log-space bug only affected the value written to disk. For steps produced
via iterative rollout (forecast-steps > 1), the un-truncated log-space values
were also fed back as the model's own input at every intermediate step, which
changes the actual forecast trajectory -- those steps must be regenerated by
re-running encode_dataset.py, not patched after the fact.

Usage:
    python fix_log_precip_step.py <step_dir> [--vars total_precipitation,olr] [--force]

Example:
    python fix_log_precip_step.py data/output/preds/awm-s2s-2x2-doy/step01
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import xarray as xr

LOG_EPS = 1e-5
DEFAULT_LOG_VARS = ["total_precipitation", "olr"]


def _is_step_finished(step_dir: Path) -> bool:
    """A step dir is considered finished if it holds as many yearly files as any
    sibling stepNN dir for the same model -- encode_dataset.py's resume logic
    fills every step to the same eventual set of years once fully done."""
    n_here = len(list(step_dir.glob("*.nc")))
    sibling_counts = [
        len(list(d.glob("*.nc"))) for d in step_dir.parent.glob("step*") if d.is_dir()
    ]
    return n_here > 0 and n_here >= max(sibling_counts, default=0)


MARKER_ATTR = "log_transform_inverted"


def fix_file(path: Path, variables: list[str]) -> bool:
    with xr.open_dataset(path, chunks="auto") as ds:
        updates = {}
        for var in variables:
            if var not in ds:
                continue
            da = ds[var]
            if da.attrs.get(MARKER_ATTR):
                print(f"  {path.name}: {var} already marked fixed, skipping.")
                continue
            physical = (np.exp(da) - LOG_EPS).clip(min=0).astype(da.dtype)
            physical.attrs = dict(da.attrs)
            physical.attrs[MARKER_ATTR] = 1
            updates[var] = physical

        if not updates:
            return False

        ds = ds.assign(updates)
        tmp_path = path.with_suffix(".nc.tmp")
        ds.to_netcdf(tmp_path, encoding={"time": {"units": "hours since 2000-01-01"}})

    tmp_path.replace(path)
    return True


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("step_dir", type=Path)
    parser.add_argument("--vars", default=",".join(DEFAULT_LOG_VARS))
    parser.add_argument("--force", action="store_true", help="Skip the 'is this step finished' check.")
    args = parser.parse_args()

    variables = [v for v in args.vars.split(",") if v]
    step_dir = args.step_dir.resolve()

    if not args.force and not _is_step_finished(step_dir):
        print(
            f"Refusing to touch {step_dir}: it doesn't look fully encoded yet "
            f"(pass --force to override).",
            file=sys.stderr,
        )
        sys.exit(1)

    files = sorted(step_dir.glob("*.nc"))
    print(f"Fixing {len(files)} file(s) in {step_dir} for variables: {variables}")
    n_fixed = 0
    for f in files:
        if fix_file(f, variables):
            n_fixed += 1
            print(f"  {f.name}: fixed.")
    print(f"Done. {n_fixed}/{len(files)} file(s) modified.")


if __name__ == "__main__":
    main()
